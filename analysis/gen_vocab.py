"""Generate program/vocab.py: the tokenizer's 2000 token strings as readable text.

The vocabulary is part of the tokenizer definition, not of the model. Tokens that are whole UTF-8
text appear as that text (" upon", "\\n"). Tokens that are a fragment of a multi-byte character
appear as "<0xE2>"-style byte names (several bytes joined, e.g. "<0xE2><0x80>").
Usage: python -m analysis.gen_vocab
"""
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)
from src.train.data import load_tokenizer  # noqa: E402


def byte_decoder():
    # GPT-2 byte-level alphabet: printable bytes map to themselves, the rest to U+0100 + n.
    bs = list(range(ord("!"), ord("~") + 1)) + list(range(ord("¡"), ord("¬") + 1)) + list(range(ord("®"), ord("ÿ") + 1))
    cs = bs[:]
    n = 0
    for b in range(256):
        if b not in bs:
            bs.append(b)
            cs.append(256 + n)
            n += 1
    return {chr(c): b for b, c in zip(bs, cs)}


def main() -> None:
    tok = load_tokenizer()
    dec = byte_decoder()
    out = []
    for i in range(tok.get_vocab_size()):
        s = tok.id_to_token(i)
        if s == "<|eos|>":
            out.append("<|eos|>")
            continue
        b = bytes(dec[c] for c in s)
        try:
            out.append(b.decode("utf-8"))
        except UnicodeDecodeError:
            out.append("".join(f"<0x{x:02X}>" for x in b))
    assert len(set(out)) == len(out), "token strings must be unique"
    lines = ['"""The tokenizer vocabulary: TOKENS[i] is the text of token id i (2000 tokens).',
             "",
             "Generated by analysis/gen_vocab.py from data/tokenizer.json (byte-level BPE fit on the train",
             "split). This is the tokenizer's definition, not a model parameter. Id 0 is the end-of-story",
             'token. Fragments of multi-byte characters are written as byte names like "<0xE2>".',
             '"""', "", "TOKENS = ["]
    row = []
    for s in out:
        row.append(repr(s))
        if sum(len(r) + 2 for r in row) > 88:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines += ["]", "", "ID = {text: i for i, text in enumerate(TOKENS)}", "VOCAB_SIZE = len(TOKENS)",
              "EOS = 0", ""]
    with open(os.path.join(REPO, "program", "vocab.py"), "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {len(out)} tokens")


if __name__ == "__main__":
    main()
