"""Head 0 attention with key-shape salience (no pair term): control for qk_h0_key_use.

Generated by analysis/investigations/qk/make_candidates.py. Attention scalars were fitted to the matching model head's
own attention pattern (cross-entropy, train_windows(32, 2024)); pattern KL on held-out train_windows(16, 2025):
head 0 key: 0.3839. Pair tables come from TRAIN corpus counts (analysis/investigations/qk/pairstats.py, build_tables.py).
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "investigations", "qk"))
import qklib  # noqa: E402

NAME = "h0_key"
HEADS = [0]
REPLACES = ['head0.self', 'head0.near', 'head0.far']
RULES = {0: ({'slope[word start]': 0.2854, 'self[word start]': 0.5666, 'slope[continuation]': 0.3673, 'self[continuation]': -0.2069, 'slope[other]': 0.1052, 'self[other]': 0.9429, 'slope[end of story]': 0.165, 'self[end of story]': 3.6455, 'key[word start]': -0.7957, 'key[continuation]': -1.1701, 'key[other]': -0.028}, True, [])}


def features(P, tokens):
    from program.readers import skipgram_votes

    s = P.STATS
    t = np.asarray(tokens, dtype=np.int64)
    out = {}
    for head, (theta, keyshape, pairs) in RULES.items():
        a = qklib.attention(head, t, s, theta, keyshape=keyshape, pairs=pairs)
        for part, unit in (("self", (1, 0, 0)), ("near", (0, 1, 0)), ("far", (0, 0, 1))):
            out[f"h{head}.{part}"] = skipgram_votes(a, t, s, *unit)
    return out
