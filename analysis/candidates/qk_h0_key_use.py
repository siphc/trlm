"""Head 0 reads an earlier token more when its skip-gram vote is useful given the current token
(corpus vote usefulness U_d(k, q) = E[PMI_{d+1}(k, next) | k at d before q] - E_{P1(.|q)}[PMI_{d+1}(k, .)],
shrunk with 20 pseudo-counts), plus key-shape salience.

Generated by analysis/investigations/qk/make_candidates.py. Attention scalars were fitted to the matching model head's
own attention pattern (cross-entropy, train_windows(32, 2024)); pattern KL on held-out train_windows(16, 2025):
head 0 key+U: 0.3499. Pair tables come from TRAIN corpus counts (analysis/investigations/qk/pairstats.py, build_tables.py).
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "investigations", "qk"))
import qklib  # noqa: E402

NAME = "h0_key_use"
HEADS = [0]
REPLACES = ['head0.self', 'head0.near', 'head0.far']
RULES = {0: ({'slope[word start]': 0.2527, 'self[word start]': 1.1431, 'slope[continuation]': 0.2816, 'self[continuation]': 0.7224, 'slope[other]': 0.0916, 'self[other]': 1.4894, 'slope[end of story]': 0.1932, 'self[end of story]': 3.5619, 'key[word start]': -0.5933, 'key[continuation]': -0.9352, 'key[other]': 0.301, 'U[d=1]': 0.361, 'U[d=2..7]': 0.3141}, True, ['U'])}


def features(P, tokens):
    from program.readers import skipgram_votes

    s = P.STATS
    t = np.asarray(tokens, dtype=np.int64)
    out = {}
    for head, (theta, keyshape, pairs) in RULES.items():
        a = qklib.attention(head, t, s, theta, keyshape=keyshape, pairs=pairs)
        for part, unit in (("self", (1, 0, 0)), ("near", (0, 1, 0)), ("far", (0, 0, 1))):
            out[f"h{head}.{part}"] = skipgram_votes(a, t, s, *unit)
    return out
