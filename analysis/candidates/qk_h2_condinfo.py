"""Head 2 reads an earlier token in proportion to how much its vote ADDS to what the current token already predicts.

The program's KEY_INFO * info_d(t_j) (how much t_j says about the token d+1 later, unconditionally) is replaced by
PAIR_USE * U_d(t_j, t_i), the same quantity conditioned on the current token (same number of scalars, 12):
    U_d(k, q) = ( sum over TRAIN occurrences of k exactly d tokens before q of PMI_(d+1)(k, next token)
                  - N_d(k, q) * sum_v P1(v | q) PMI_(d+1)(k, v) ) / (N_d(k, q) + 20),   d = 1..7 (0 otherwise)
i.e. how much better k's skip-gram vote fits what actually follows (k ... q) than what q alone predicts.

Generated by analysis/investigations/qk (attnfit.py variant 'noinfo+U*'). Attention scalars fitted to model head 2's
own attention pattern (train_windows(32, 2024)); pattern KL on held-out train_windows(16, 2025): 0.4433
(program rule 0.4522).
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "investigations", "qk"))
import qklib  # noqa: E402

NAME = "h2_condinfo"
HEADS = [2]
REPLACES = ["head2.self", "head2.near", "head2.far"]
THETA = {'SELF_BASE': -0.2772, 'SELF_INFO': 0.3724, 'SELF_CONT': 0.9225, 'SELF_PIECE': -1.1733, 'DECAY': 0.2879, 'DECAY_FAR': 0.1118, 'PREVIOUS': 0.0924, 'KEY_CONT': -1.3323, 'KEY_PIECE': -1.3985, 'KEY_SPACE': -0.4381, 'KEY_SENTENCE_END': 0.8128, 'U[d=1..7]': 0.3846}


def features(P, tokens):
    from program.readers import skipgram_votes

    t = np.asarray(tokens, dtype=np.int64)
    a = qklib.attention(2, t, P.STATS, THETA, pairs=["U*"], noinfo=True)
    return {part: skipgram_votes(a, t, P.STATS, *unit)
            for part, unit in (("self", (1, 0, 0)), ("near", (0, 1, 0)), ("far", (0, 0, 1)))}
