"""Head 2 reads an earlier token more when its skip-gram vote is useful given the current token, with ONE
scalar for d = 1..7: score += PAIR_USE * U_d(t_j, t_i), U_d(k, q) = (sum over corpus occurrences of k d tokens
before q of PMI_{d+1}(k, next) - N_d(k, q) * E_{P1(.|q)}[PMI_{d+1}(k, .)]) / (N_d(k, q) + 20).

Generated by analysis/investigations/qk/make_candidates.py. Attention scalars were fitted to the matching model head's
own attention pattern (cross-entropy, train_windows(32, 2024)); pattern KL on held-out train_windows(16, 2025):
head 2 base+U*: 0.4399. Pair tables come from TRAIN corpus counts (analysis/investigations/qk/pairstats.py, build_tables.py).
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "investigations", "qk"))
import qklib  # noqa: E402

NAME = "h2_use1"
HEADS = [2]
REPLACES = ['head2.self', 'head2.near', 'head2.far']
RULES = {2: ({'SELF_BASE': -0.2188, 'SELF_INFO': 0.3936, 'SELF_CONT': 0.8313, 'SELF_PIECE': -1.164, 'DECAY': 0.2818, 'DECAY_FAR': 0.1134, 'PREVIOUS': -0.0185, 'KEY_INFO': 0.2123, 'KEY_CONT': -1.383, 'KEY_PIECE': -1.3094, 'KEY_SPACE': -0.4107, 'KEY_SENTENCE_END': 0.8452, 'U[d=1..7]': 0.3085}, False, ['U*'])}


def features(P, tokens):
    from program.readers import skipgram_votes

    s = P.STATS
    t = np.asarray(tokens, dtype=np.int64)
    out = {}
    for head, (theta, keyshape, pairs) in RULES.items():
        a = qklib.attention(head, t, s, theta, keyshape=keyshape, pairs=pairs)
        for part, unit in (("self", (1, 0, 0)), ("near", (0, 1, 0)), ("far", (0, 0, 1))):
            out[f"h{head}.{part}"] = skipgram_votes(a, t, s, *unit)
    return out
