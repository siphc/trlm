"""Write candidate files analysis/candidates/qk_<name>.py with attention scalars taken from attnfit_h{0,2}.json."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
CAND = os.path.join(HERE, "..", "..", "candidates")

TEMPLATE = '''"""{doc}

Generated by analysis/investigations/qk/make_candidates.py. Attention scalars were fitted to the matching model head's
own attention pattern (cross-entropy, train_windows(32, 2024)); pattern KL on held-out train_windows(16, 2025):
{pkl}. Pair tables come from TRAIN corpus counts (analysis/investigations/qk/pairstats.py, build_tables.py).
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "investigations", "qk"))
import qklib  # noqa: E402

NAME = "{name}"
HEADS = {heads}
REPLACES = {replaces}
RULES = {rules}


def features(P, tokens):
    from program.readers import skipgram_votes

    s = P.STATS
    t = np.asarray(tokens, dtype=np.int64)
    out = {{}}
    for head, (theta, keyshape, pairs) in RULES.items():
        a = qklib.attention(head, t, s, theta, keyshape=keyshape, pairs=pairs)
        for part, unit in (("self", (1, 0, 0)), ("near", (0, 1, 0)), ("far", (0, 0, 1))):
            out[f"h{{head}}.{{part}}"] = skipgram_votes(a, t, s, *unit)
    return out
'''


def make(name, doc, specs):
    rules, pk, heads, repl = {}, [], [], []
    for head, var in specs:
        r = json.load(open(os.path.join(HERE, f"attnfit_h{head}.json")))[var]
        parts = var.split("+")
        pairs = [p for p in parts if p not in ("base", "key", "prog")]
        rules[head] = (r["theta"], "key" in parts, pairs)
        pk.append(f"head {head} {var}: {r['pattern_kl_eval']}")
        heads.append(head)
        repl += [f"head{head}.self", f"head{head}.near", f"head{head}.far"]
    src = TEMPLATE.format(doc=doc, pkl="; ".join(pk), name=name, heads=heads, replaces=repl, rules=repr(rules))
    path = os.path.join(CAND, f"qk_{name}.py")
    open(path, "w").write(src)
    print(path)


if __name__ == "__main__":
    make("h0_key", "Head 0 attention with key-shape salience (no pair term): control for qk_h0_key_use.", [(0, "key")])
    make("h0_key_use", "Head 0 reads an earlier token more when its skip-gram vote is useful given the current token\n"
         "(corpus vote usefulness U_d(k, q) = E[PMI_{d+1}(k, next) | k at d before q] - E_{P1(.|q)}[PMI_{d+1}(k, .)],\n"
         "shrunk with 20 pseudo-counts), plus key-shape salience.", [(0, "key+U")])
    make("h2_use", "Head 2 reads an earlier token more when its skip-gram vote is useful given the current token\n"
         "(corpus vote usefulness U_d, see qk_h0_key_use).", [(2, "base+U")])
    make("h02_use", "Heads 0 and 2 with the vote-usefulness pair term (qk_h0_key_use + qk_h2_use).", [(0, "key+U"), (2, "base+U")])
    make("h0_prog", "Control: head 0's program rule re-expressed as a candidate (paired diff should be 0; R^2 baseline\n"
         "with the same three directions).", [(0, "prog")])
    make("h2_prog", "Control: head 2's program rule re-expressed as a candidate.", [(2, "prog")])
